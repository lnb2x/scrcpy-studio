export type TranslationKey = keyof typeof translations.en;

interface I18nStore {
  language: AppLanguage;
  setLanguage: (lang: AppLanguage) => void;
  t: (key: TranslationKey) => string;
  tf: (key: TranslationKey, params: Record<string, string | number>) => string;
}

/** Replaces `{placeholder}` tokens in a translation string. */
export function formatTranslation(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match
  );
}

export const useI18nStore = create<I18nStore>((set, get) => ({
  language: 'en',
  setLanguage: (lang) => {
    localStorage.setItem('scrcpy-language', lang);
    set({ language: lang });
  },
  t: (key) => {
    const lang = get().language;
    const dict = translations[lang] || translations.en;
    return dict[key] || translations.en[key] || (key as string);
  },
  tf: (key, params) => formatTranslation(get().t(key), params),
}));

export function useTranslation() {
  const { t, tf, language, setLanguage } = useI18nStore();
  return { t, tf, language, setLanguage };
}
